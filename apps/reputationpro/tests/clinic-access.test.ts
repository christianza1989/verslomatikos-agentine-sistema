test('clinic credentials and sessions isolate tenants and require Stripe activation',()=>{
  const a=createClient({business_name:'Clinic One',email:'one@example.test',slug:'clinic-one',google_review_url:'https://www.google.com/maps'});
  const b=createClient({business_name:'Clinic Two',email:'two@example.test',slug:'clinic-two',google_review_url:'https://www.google.com/maps'});
  const password='very-long-test-password';createClinicCredential(a.id,password);createClinicCredential(b.id,password);
  const saved=db().prepare('SELECT * FROM clinic_credentials WHERE client_id=?').get(a.id)!;
  const savedB=db().prepare('SELECT * FROM clinic_credentials WHERE client_id=?').get(b.id)!;
  assert.notEqual(saved.password_hash,password);assert.notEqual(saved.password_hash,savedB.password_hash);
  assert.equal(verifyClinicPassword(a.id,password),true);assert.equal(verifyClinicPassword(a.id,'incorrect-password'),false);
  assert.equal(authenticateClinic(a.email,password),null);
  assert.equal(canCollectFeedback(getClientById(a.id)!),false);
  db().prepare("UPDATE clients SET stripe_subscription_id='sub_test',subscription_status='trialing' WHERE id=?").run(a.id);
  assert.equal(authenticateClinic(a.email,password),null,'email ownership must also be verified');
  db().prepare('INSERT INTO clinic_email_verifications(client_id,verified_at) VALUES (?,?)').run(a.id,Date.now());
  assert.equal(authenticateClinic(a.email,password),a.id);assert.equal(authenticateClinic(a.email,'incorrect-password'),null);
  assert.equal(canCollectFeedback(getClientById(a.id)!),true);
  const session=issueClinicSession(a.id);assert.equal(clinicSession(session.token),a.id);
  const principal={role:'clinic' as const,clientId:a.id};
  assert.equal(canAccessClient(principal,a.id),true);assert.equal(canAccessClient(principal,b.id),false);
  assert.equal(canAccessClient({role:'owner'},b.id),true);
  db().prepare("UPDATE clients SET subscription_status='canceled' WHERE id=?").run(a.id);
  assert.equal(canCollectFeedback(getClientById(a.id)!),false);
  assert.equal(clinicSession(session.token),a.id,'customer retains account access to manage billing');
  revokeClinicSession(session.token);assert.equal(clinicSession(session.token),null);
});
